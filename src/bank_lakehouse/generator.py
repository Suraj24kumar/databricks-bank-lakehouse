"""Deterministic synthetic data generator: one landing "day" per call, no external data needed.

Why synthetic: Databricks Free Edition restricts outbound internet, and we need *changing*
data (customer updates, deletes, late/duplicate/dirty transactions) to demonstrate incremental
loads and SCD2. State is rebuilt by replaying days 0..N with a seeded RNG, so any day can be
regenerated byte-for-byte (idempotent landing).

Feeds written per day (CSV with header) under <root>/<feed>/dt=YYYY-MM-DD/<feed>_<date>.csv:
  customers     CDC feed: op = UPSERT | DELETE, updated_at  -> SCD2 in silver
  accounts      CDC feed (same shape)                       -> SCD1 in silver
  transactions  append-only facts, with planted faults      -> dedupe + quarantine
"""

from __future__ import annotations

import csv
import random
from dataclasses import dataclass, field
from datetime import date, datetime, timedelta
from pathlib import Path

CITIES = ["Kuala Lumpur", "Bengaluru", "Mumbai", "Singapore", "Jakarta", "Manila"]
SEGMENTS = ["RETAIL", "PREMIUM", "SME"]
KYC = ["PENDING", "VERIFIED", "EXPIRED"]
RISK = ["LOW", "MEDIUM", "HIGH"]
ACCOUNT_TYPES = ["SAVINGS", "CURRENT", "CREDIT"]
ACCOUNT_STATUS = ["ACTIVE", "DORMANT", "FROZEN"]
CHANNELS = ["ATM", "POS", "ONLINE", "BRANCH", "UPI"]
TXN_TYPES = ["DEBIT", "CREDIT"]

CUSTOMER_COLS = ["customer_id", "name", "email", "city", "segment", "kyc_status", "risk_band", "op", "updated_at"]
ACCOUNT_COLS = ["account_id", "customer_id", "account_type", "status", "op", "updated_at"]
TXN_COLS = ["txn_id", "account_id", "customer_id", "txn_ts", "amount", "currency", "channel", "txn_type"]

START_DATE = date(2026, 1, 1)
INITIAL_CUSTOMERS = 300
TXNS_PER_DAY = 1500


@dataclass
class World:
    customers: dict = field(default_factory=dict)  # id -> attribute dict (live customers only)
    accounts: dict = field(default_factory=dict)
    next_customer: int = 1
    next_account: int = 1
    next_txn: int = 1


def _ts(d: date, rng: random.Random) -> str:
    return (datetime.combine(d, datetime.min.time()) + timedelta(seconds=rng.randint(0, 86399))).strftime("%Y-%m-%d %H:%M:%S")


def _new_customer(w: World, rng: random.Random, d: date, out_c: list, out_a: list) -> None:
    cid = f"C{w.next_customer:06d}"
    w.next_customer += 1
    cust = {
        "customer_id": cid, "name": f"Customer {cid}", "email": f"{cid.lower()}@example.com",
        "city": rng.choice(CITIES), "segment": rng.choices(SEGMENTS, [6, 3, 1])[0],
        "kyc_status": rng.choices(KYC, [2, 7, 1])[0], "risk_band": rng.choices(RISK, [6, 3, 1])[0],
    }
    w.customers[cid] = cust
    out_c.append({**cust, "op": "UPSERT", "updated_at": _ts(d, rng)})
    for _ in range(rng.choice([1, 1, 2])):
        aid = f"A{w.next_account:07d}"
        w.next_account += 1
        acc = {"account_id": aid, "customer_id": cid, "account_type": rng.choice(ACCOUNT_TYPES), "status": "ACTIVE"}
        w.accounts[aid] = acc
        out_a.append({**acc, "op": "UPSERT", "updated_at": _ts(d, rng)})


def _step(w: World, day: int) -> tuple[list, list, list]:
    """Advance the world by one day; return (customer_changes, account_changes, transactions)."""
    d = START_DATE + timedelta(days=day)
    rng = random.Random(f"bank-{day}")
    cust_out: list = []
    acc_out: list = []

    if day == 0:
        for _ in range(INITIAL_CUSTOMERS):
            _new_customer(w, rng, d, cust_out, acc_out)
    else:
        for _ in range(rng.randint(3, 8)):  # new customers
            _new_customer(w, rng, d, cust_out, acc_out)
        live = sorted(w.customers)
        for cid in rng.sample(live, k=max(1, len(live) // 12)):  # ~8% change a tracked attribute (SCD2 history)
            c = w.customers[cid]
            field_name = rng.choice(["city", "segment", "kyc_status", "risk_band"])
            pool = {"city": CITIES, "segment": SEGMENTS, "kyc_status": KYC, "risk_band": RISK}[field_name]
            c[field_name] = rng.choice([v for v in pool if v != c[field_name]])
            cust_out.append({**c, "op": "UPSERT", "updated_at": _ts(d, rng)})
        for cid in rng.sample(live, k=max(1, len(live) // 40)):  # email change: untracked -> in-place update, no new version
            c = w.customers[cid]
            c["email"] = f"{cid.lower()}.{day}@example.com"
            cust_out.append({**c, "op": "UPSERT", "updated_at": _ts(d, rng)})
        if day % 5 == 0 and len(live) > 50:  # a customer leaves the bank
            cid = rng.choice(live)
            c = w.customers.pop(cid)
            cust_out.append({**c, "op": "DELETE", "updated_at": _ts(d, rng)})
        for aid in rng.sample(sorted(w.accounts), k=max(1, len(w.accounts) // 30)):  # account status change (SCD1)
            a = w.accounts[aid]
            a["status"] = rng.choice(ACCOUNT_STATUS)
            acc_out.append({**a, "op": "UPSERT", "updated_at": _ts(d, rng)})

    txns: list = []
    live_accounts = sorted(a for a, v in w.accounts.items() if v["customer_id"] in w.customers)
    for _ in range(TXNS_PER_DAY):
        aid = rng.choice(live_accounts)
        late = rng.random() < 0.02  # 2% arrive a day late: event time is yesterday
        ev_day = d - timedelta(days=1) if (late and day > 0) else d
        txns.append({
            "txn_id": f"T{w.next_txn:09d}", "account_id": aid, "customer_id": w.accounts[aid]["customer_id"],
            "txn_ts": _ts(ev_day, rng), "amount": f"{rng.uniform(1, 5000):.2f}", "currency": "MYR",
            "channel": rng.choice(CHANNELS), "txn_type": rng.choice(TXN_TYPES),
        })
        w.next_txn += 1
    return cust_out, acc_out, txns


def plant_faults(txns: list, prev_txns: list, day: int) -> tuple[list, dict]:
    """Corrupt a known number of rows so tests/DQ can assert exact counts. Faults are deterministic per day."""
    rng = random.Random(f"faults-{day}")
    txns = [dict(t) for t in txns]
    idx = rng.sample(range(len(txns)), k=12)
    for i in idx[0:3]:
        txns[i]["account_id"] = ""  # null_account
    for i in idx[3:6]:
        txns[i]["amount"] = f"-{abs(float(txns[i]['amount'])):.2f}"  # negative_amount
    for i in idx[6:9]:
        txns[i]["channel"] = "FAX"  # unknown_channel
    for i in idx[9:12]:
        txns[i]["txn_ts"] = "2026-13-45 25:61:00"  # bad_timestamp
    replays = rng.sample(prev_txns, k=5) if prev_txns else []  # at-least-once delivery: yesterday's rows again
    return txns + [dict(r) for r in replays], {
        "null_account": 3, "negative_amount": 3, "unknown_channel": 3, "bad_timestamp": 3, "replayed_duplicates": len(replays),
    }


def generate_day(day: int, root: str | Path) -> dict:
    """Write the three landing files for `day` and return the planted-fault manifest (also written as JSON-ish text)."""
    w = World()
    prev_txns: list = []
    cust = acc = txns = []
    for d in range(day + 1):
        cust, acc, txns = _step(w, d)
        if d < day:
            prev_txns = txns
    txns_final, manifest = plant_faults(txns, prev_txns, day)
    label = (START_DATE + timedelta(days=day)).isoformat()
    root = Path(root)
    for feed, cols, rows in (("customers", CUSTOMER_COLS, cust), ("accounts", ACCOUNT_COLS, acc), ("transactions", TXN_COLS, txns_final)):
        folder = root / feed / f"dt={label}"
        folder.mkdir(parents=True, exist_ok=True)
        path = folder / f"{feed}_{label}.csv"
        tmp = path.with_suffix(".tmp")
        with open(tmp, "w", newline="") as fh:
            writer = csv.DictWriter(fh, fieldnames=cols)
            writer.writeheader()
            writer.writerows(rows)
        tmp.replace(path)  # same bytes every time for the same day
    manifest.update({"day": day, "date": label, "customer_changes": len(cust), "account_changes": len(acc), "transactions_landed": len(txns_final)})
    return manifest
